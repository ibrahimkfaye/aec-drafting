#!/usr/bin/env node
/**
 * Writes .env.local from your LOCAL Supabase stack (`npx supabase status -o env`),
 * so you never have to copy keys by hand. Local keys only — never use for hosted projects.
 *
 *   npm run env:local            # creates .env.local if it does not exist
 *   npm run env:local -- --force # replaces an existing .env.local (asks nothing; be sure)
 *
 * Prints variable NAMES only, never values.
 */
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";

const force = process.argv.includes("--force");
if (existsSync(".env.local") && !force) {
  console.log(".env.local already exists — left unchanged. Re-run with `-- --force` to replace it.");
  process.exit(0);
}

let raw;
try {
  raw = execFileSync("npx", ["supabase", "status", "-o", "env"], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
} catch {
  console.error("Could not read local Supabase status. Is Docker running and did you run `npm run db:start`?");
  process.exit(1);
}

const vars = {};
for (const line of raw.split("\n")) {
  const m = line.match(/^([A-Z0-9_]+)=(?:"(.*)"|(.*))$/);
  if (m) vars[m[1]] = m[2] ?? m[3];
}
const pick = (...names) => names.map((n) => vars[n]).find(Boolean);

const apiUrl = pick("API_URL");
const publishable = pick("PUBLISHABLE_KEY", "ANON_KEY");
const secret = pick("SECRET_KEY", "SERVICE_ROLE_KEY");

if (!apiUrl || !publishable || !secret) {
  console.error("Unexpected `supabase status` output. Variable names found:", Object.keys(vars).join(", "));
  process.exit(1);
}
const host = new URL(apiUrl).hostname;
if (!["127.0.0.1", "localhost"].includes(host)) {
  console.error(`Refusing: API_URL is not local (${host}).`);
  process.exit(1);
}

writeFileSync(
  ".env.local",
  `# Generated by scripts/local-env.mjs for LOCAL development. Git-ignored. Do not share.
NEXT_PUBLIC_SUPABASE_URL=${apiUrl}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable}
# SERVER-ONLY (bypasses row-level security). Used only by scripts/seed-local.ts.
SUPABASE_SECRET_KEY=${secret}
`,
  { mode: 0o600 },
);
console.log("Wrote .env.local with NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY, SUPABASE_SECRET_KEY.");
